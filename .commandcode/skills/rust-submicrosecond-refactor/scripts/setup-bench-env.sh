#!/usr/bin/env bash
# Scaffold a production-grade local bench environment under .bench-env/
# and optionally inventory third-party deps via thirdparty-e2e.
#
# Usage:
#   setup-bench-env.sh <project-root> [--inventory] [--up] [--force]
#
# Exit: 0 ok, 1 failure, 2 bad args.
set -euo pipefail

root=""
do_inventory=0
do_up=0
force=0

for arg in "$@"; do
  case "$arg" in
    --inventory) do_inventory=1 ;;
    --up) do_up=1 ;;
    --force) force=1 ;;
    -h|--help)
      echo "usage: setup-bench-env.sh <project-root> [--inventory] [--up] [--force]" >&2
      exit 2
      ;;
    -*)
      echo "error: unknown option $arg" >&2
      exit 2
      ;;
    *)
      root="$arg"
      ;;
  esac
done
root="${root:-.}"

if [ ! -d "$root" ]; then
  echo "error: project root not found: $root" >&2
  exit 2
fi

skill_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$root/.bench-env"
tp_skill="$(cd "$skill_dir/../thirdparty-e2e" 2>/dev/null && pwd || true)"

if [ -d "$out" ] && [ "$force" -ne 1 ]; then
  echo "error: $out exists (pass --force to rebuild scaffold)" >&2
  exit 1
fi

mkdir -p "$out/fixtures" "$out/wiremock/mappings" "$out/profiles"
cp "$skill_dir/assets/docker-compose.bench.yml" "$out/docker-compose.yml"
cp "$skill_dir/assets/toxiproxy.json" "$out/toxiproxy.json"
cp "$skill_dir/assets/wiremock/mappings/health.json" "$out/wiremock/mappings/health.json"

# Profile recipes (applied by the agent / toxiproxy CLI — documented, not auto-applied).
cat > "$out/profiles/baseline-zero.md" <<'MD'
# baseline-zero
No Toxiproxy toxics. WireMock fixedDelayMilliseconds: 0 on all stubs.
Use for dual-gate ACCEPT/REJECT of code changes.
MD

cat > "$out/profiles/prod-like.md" <<'MD'
# prod-like
Document each provider's p50/p99 from observability or SLA in .devflow/bench-env.md.
Example Toxiproxy toxic (latency):
  toxiproxy-cli toxic add provider_via_proxy -t latency -a latency=50 -a jitter=10
Replace 50/10 with measured values — do not invent them.
MD

cat > "$out/profiles/fault.md" <<'MD'
# fault
Bounded faults for resilience benches only (not the primary dual-gate unless that is the hypothesis).
Example: timeout toxic or WireMock 503/429 stubs alongside happy-path fixtures.
MD

cat > "$out/README.md" <<'MD'
# .bench-env

Generated by rust-submicrosecond-refactor `setup-bench-env.sh`.
Fill fixtures under `fixtures/` and WireMock mappings under `wiremock/mappings/`.
Point the SUT at Toxiproxy listen ports (see toxiproxy.json), never at production.
MD

# Softflow artifact draft (agent fills and marks complete after check).
devflow_dir="$root/.devflow"
if [ -d "$devflow_dir" ] || [ -f "$root/.devflow/plan.md" ]; then
  mkdir -p "$devflow_dir"
  if [ ! -f "$devflow_dir/bench-env.md" ] || [ "$force" -eq 1 ]; then
    today="$(date +%F)"
    sed "s/YYYY-MM-DD/$today/" "$skill_dir/assets/bench-env.md" > "$devflow_dir/bench-env.md"
    # keep draft until check passes
    awk 'BEGIN{fm=0}
      /^---[[:space:]]*$/{fm++; print; next}
      fm==1 && /^status:/{print "status: draft"; next}
      {print}' "$devflow_dir/bench-env.md" > "$devflow_dir/bench-env.md.tmp"
    mv "$devflow_dir/bench-env.md.tmp" "$devflow_dir/bench-env.md"
    echo "wrote: $devflow_dir/bench-env.md (status: draft)"
  fi
fi

if [ "$do_inventory" -eq 1 ]; then
  if [ -n "$tp_skill" ] && [ -x "$tp_skill/scripts/inventory.sh" ]; then
    echo "== thirdparty-e2e inventory =="
    bash "$tp_skill/scripts/inventory.sh" "$root" || {
      echo "WARN: inventory.sh failed — record gaps in bench-env.md; do not invent providers" >&2
    }
  else
    echo "WARN: thirdparty-e2e not installed beside this skill; skip --inventory" >&2
  fi
fi

if [ "$do_up" -eq 1 ]; then
  if ! command -v docker >/dev/null 2>&1; then
    echo "error: docker required for --up" >&2
    exit 1
  fi
  docker compose -p bench -f "$out/docker-compose.yml" up -d --wait
fi

echo "scaffolded: $out"
echo "next: fill fixtures, point the app at toxiproxy ports, run check-bench-env.sh, then mark .devflow/bench-env.md complete"
