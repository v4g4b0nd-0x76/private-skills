#!/usr/bin/env bash
# Scaffold a runnable adversarial test suite for a backend.
# Usage: gen-suite.sh [backend-root] [--out DIR] [--force]
set -euo pipefail

skill_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
root="."
out=".security/suite"
force=0

usage() {
  cat >&2 <<'EOF'
usage: gen-suite.sh [backend-root] [--out DIR] [--force]
  --out DIR   where to write the suite (default .security/suite)
  --force     overwrite an existing suite directory
EOF
  exit 1
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --out) out="${2:-}"; shift 2 ;;
    --force) force=1; shift ;;
    -h|--help) usage ;;
    -*) echo "error: unknown option '$1'" >&2; usage ;;
    *) root="$1"; shift ;;
  esac
done

if [ ! -d "$root" ]; then
  echo "error: backend root not found: $root" >&2
  exit 2
fi

dest="$root/$out"
if [ -e "$dest" ] && [ "$force" -eq 0 ]; then
  echo "error: $dest already exists (pass --force to overwrite)" >&2
  exit 1
fi
[ "$force" -eq 1 ] && rm -rf "$dest"
mkdir -p "$dest"

copy() {
  local src="$1" dst="$2"
  if [ ! -f "$skill_dir/assets/suite/$src" ]; then
    echo "error: missing template assets/suite/$src" >&2
    exit 1
  fi
  cp "$skill_dir/assets/suite/$src" "$dest/$dst"
  echo "created $out/$dst"
}

copy conftest.py conftest.py
copy test_authn.py test_authn.py
copy test_authz_bola.py test_authz_bola.py
copy test_privesc.py test_privesc.py
copy test_mass_assign.py test_mass_assign.py
copy test_race.py test_race.py
copy test_leakage.py test_leakage.py

cat > "$dest/README.md" <<'MD'
# Adversarial backend test suite

Generated by the `backend-security-test` skill.

## Run

```bash
export BASE_URL=http://localhost:8080
export ALICE_USER=alice@example.test ALICE_PASS=...
export BOB_USER=bob@example.test     BOB_PASS=...
python -m pytest .security/suite -x -q
```

## Rules

- Only run against a system you own. `BASE_URL` must be local.
- Every authorization test needs two principals that own different objects.
- Fill the `TODO` markers with real object ids from your fixtures; the suite
  fails loudly on `NotImplementedError` rather than silently passing.
- A test that cannot assert on state should be deleted, not weakened.

## What is covered

| File | Class |
|---|---|
| test_authn.py | token/session validation, expiry, tampering |
| test_authz_bola.py | the six BOLA families, all verbs |
| test_privesc.py | vertical escalation, role manipulation |
| test_mass_assign.py | ownership fields, privilege fields |
| test_race.py | TOCTOU / duplicate action under concurrency |
| test_leakage.py | over-fetch, error disclosure, caching |
MD

echo ""
echo "suite written to $dest"
echo ""
echo "next:"
echo "  1. fill the TODO markers from .security/surface.md"
echo "  2. export BASE_URL to your LOCAL dev server and run pytest"
echo "  3. every finding needs reproduction + observed wrong state (see assets/report.md)"
