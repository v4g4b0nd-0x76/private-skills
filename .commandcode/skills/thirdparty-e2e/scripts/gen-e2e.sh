#!/usr/bin/env bash
# Generate a third-party E2E suite plus docker-compose for WireMock + Toxiproxy.
# Usage: gen-e2e.sh [app-root] [--out DIR] [--force]
set -euo pipefail

skill_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
root="."
out=".thirdparty/e2e"
force=0

usage() {
  cat >&2 <<'EOF'
usage: gen-e2e.sh [app-root] [--out DIR] [--force]
  --out DIR   where to write the suite (default .thirdparty/e2e)
  --force     overwrite existing files
EOF
  exit 1
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --out) out="${2:-}"; shift 2 ;;
    --force) force=1; shift ;;
    -h|--help) usage ;;
    -*) echo "error: unknown option '$1'" >&2; usage ;;
    *) root="$1"; shift ;;
  esac
done

[ -d "$root" ] || { echo "error: app root not found: $root" >&2; exit 2; }

dest="$root/$out"
if [ -e "$dest" ] && [ "$force" -eq 0 ]; then
  echo "error: $dest already exists (pass --force to overwrite)" >&2
  exit 1
fi
[ "$force" -eq 1 ] && rm -rf "$dest"
mkdir -p "$dest" "$root/.thirdparty"

copy() {
  local src="$1" dst="$2"
  [ -f "$skill_dir/assets/e2e/$src" ] || { echo "error: missing assets/e2e/$src" >&2; exit 1; }
  cp "$skill_dir/assets/e2e/$src" "$dest/$dst"
  echo "created $out/$dst"
}

copy conftest.py conftest.py
copy test_contracts.py test_contracts.py
copy test_failures.py test_failures.py
copy test_resilience.py test_resilience.py
copy test_degradation.py test_degradation.py

compose="$root/.thirdparty/docker-compose.yml"
if [ -f "$compose" ] && [ "$force" -eq 0 ]; then
  echo "keep  .thirdparty/docker-compose.yml (exists)"
else
  [ -f "$skill_dir/assets/docker-compose.yml" ] || { echo "error: missing assets/docker-compose.yml" >&2; exit 1; }
  cp "$skill_dir/assets/docker-compose.yml" "$compose"
  echo "created .thirdparty/docker-compose.yml"
fi

req="$root/.thirdparty/requirements.md"
if [ -f "$req" ]; then
  echo "keep  .thirdparty/requirements.md (exists)"
else
  cp "$skill_dir/assets/integration-requirements.md" "$req"
  echo "created .thirdparty/requirements.md (fill this first)"
fi

cat > "$dest/README.md" <<'MD'
# Third-party E2E suite

Generated by the `thirdparty-e2e` skill.

## Run

```bash
cd .thirdparty && docker compose up -d      # WireMock :8080, Toxiproxy :8474
export APP_URL=http://localhost:3000
python -m pytest .thirdparty/e2e -q
```

## Rules

- Only run against a system you own. `APP_URL` must be local.
- Every test must assert on **behaviour**, not just status codes.
- Unfilled TODOs raise instead of passing: a security-free green suite is a lie.
- Read `../requirements.md` before writing an assertion; it holds the contracts.

## Coverage

| File | Hunts for |
|---|---|
| test_contracts.py | schema drift, required fields, versioning |
| test_failures.py | silent success, retry storms, wrong fallback |
| test_resilience.py | idempotency, timeout mismatch, token refresh |
| test_degradation.py | partial outage behaviour, backlog drain |
MD

echo ""
echo "suite written to $dest"
echo "next:"
echo "  1. fill .thirdparty/requirements.md for each provider"
echo "  2. fill the TODOs in each test file"
echo "  3. bash $skill_dir/scripts/loadgen.sh <root> --generate"
